public class Senjata {
    private String nama;
    private int bonusDamage;


    public Senjata(String nama, int bonusDamage) {
        this.nama = nama;
        this.bonusDamage = bonusDamage;
    }


    public String getNama() {
        return nama;
    }


    public int getBonusDamage() {
        return bonusDamage;
    }

}
