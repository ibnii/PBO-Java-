public class Studio {
    private String nama;
    private int tarifSewaPerJam;

    public Studio(String nama, int tarifSewaPerJam) {
        this.nama = nama;
        this.tarifSewaPerJam = tarifSewaPerJam;
    }

    public String getNama() {
        return nama;
    }

    public int getTarifSewaPerJam() {
        return tarifSewaPerJam;
    }

}
