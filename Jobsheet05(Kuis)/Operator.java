public class Operator {
    private String nama;
    private int biayaLayananPerTiket;

    public Operator(String nama, int biayaLayananPerTiket) {
        this.nama = nama;
        this.biayaLayananPerTiket = biayaLayananPerTiket;
    }

    public String getNama() {
        return nama;
    }

    public int getBiayaLayananPerTiket() {
        return biayaLayananPerTiket;
    }
}
